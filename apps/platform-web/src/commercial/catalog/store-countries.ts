let names: Intl.DisplayNames | null = null;

/** "India" for IN (the browser's English region name; the code itself when unavailable). */
export function countryName(code: string): string {
  try {
    names ??= new Intl.DisplayNames(['en'], { type: 'region' });
    return names.of(code) ?? code;
  } catch {
    return code;
  }
}

/** The selectable countries (US excluded: its price is the plan's list price), sorted by name. */
export function storeCountryOptions(): { code: string; name: string; currency: string }[] {
  return Object.entries(STORE_COUNTRY_CURRENCY)
    .filter(([code]) => code !== 'US')
    .map(([code, currency]) => ({ code, name: countryName(code), currency }))
    .sort((a, b) => a.name.localeCompare(b.name));
}
