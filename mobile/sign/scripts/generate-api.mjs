#!/usr/bin/env node
// Generates the typed API surface for the Aramo Sign mobile app from the repo's
// OpenAPI documents (directive §2 "Shared contracts"):
//   ../../openapi/sign.yaml  -> src/api/generated/sign.ts
//   ../../openapi/auth.yaml  -> src/api/generated/auth.ts
//
//   npm run generate:api     regenerate (commit the result)
//   npm run check:api        CI drift check: exit 1 if a checked-in file is stale
//
// Only TYPES are generated; runtime behaviour lives in src/api/*.ts.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repo = resolve(root, '..', '..');
const outDir = resolve(root, 'src/api/generated');

const SPECS = [
  { name: 'sign', spec: resolve(repo, 'openapi/sign.yaml') },
  { name: 'auth', spec: resolve(repo, 'openapi/auth.yaml') },
];

const check = process.argv.includes('--check');

// The repo's vocabulary gate (scripts/verify-vocabulary.sh) scans mobile/. Shared
// OpenAPI components carry prose that the gate exempts at its source file but not
// in a copy, so any generated doc comment that matches a gated term is dropped.
// The term list is read from the gate itself (never restated here).
async function gatedTermsRegex() {
  const script = await readFile(resolve(repo, 'scripts/verify-vocabulary.sh'), 'utf8');
  const block = script.match(/TIER2_TERMS_REGEX=\(([\s\S]*?)\n\)/);
  if (!block) throw new Error('TIER2_TERMS_REGEX not found in scripts/verify-vocabulary.sh');
  const patterns = [...block[1].matchAll(/"[^:"]+:([^"]+)"/g)].map((m) =>
    m[1].replace(/\\\\/g, '\\'),
  );
  if (patterns.length === 0) throw new Error('no gated terms parsed');
  return new RegExp(patterns.join('|'), 'i');
}

function dropGatedComments(source, gated) {
  const lines = source.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    if (line.trimStart().startsWith('/**')) {
      let end = i;
      while (end < lines.length && !lines[end].includes('*/')) end += 1;
      const blockLines = lines.slice(i, end + 1);
      if (!gated.test(blockLines.join('\n'))) out.push(...blockLines);
      i = end;
      continue;
    }
    out.push(line);
  }
  return out.join('\n');
}

async function render({ name, spec }, gated) {
  const ast = await openapiTS(pathToFileURL(spec), {
    // Stable output: no timestamps, alphabetical enums untouched, readonly off.
    alphabetize: false,
    exportType: false,
  });
  const header =
    '/* eslint-disable */\n' +
    `// GENERATED by scripts/generate-api.mjs from ${relative(root, spec)}. Do not edit.\n` +
    '// Regenerate with `npm run generate:api`.\n\n';
  return {
    name,
    file: resolve(outDir, `${name}.ts`),
    source: header + dropGatedComments(astToString(ast), gated),
  };
}

const gated = await gatedTermsRegex();
const results = await Promise.all(SPECS.map((s) => render(s, gated)));
let stale = 0;
await mkdir(outDir, { recursive: true });
for (const r of results) {
  if (check) {
    const current = await readFile(r.file, 'utf8').catch(() => '');
    if (current !== r.source) {
      stale += 1;
      console.error(`stale: ${relative(root, r.file)} (run npm run generate:api)`);
    }
  } else {
    await writeFile(r.file, r.source);
    console.log(`wrote ${relative(root, r.file)}`);
  }
}
if (check) {
  if (stale > 0) process.exit(1);
  console.log(`generated API types are current (${results.length} files)`);
}
